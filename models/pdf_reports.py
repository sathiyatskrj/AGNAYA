def _build_styles() -> Dict[str, ParagraphStyle]:
    """Constructs clean typographical styles for executive PDF briefs."""
    base = getSampleStyleSheet()
    styles = {
        "title": ParagraphStyle(
            "DocTitle",
            parent=base["Normal"],
            fontName="Helvetica-Bold",
            fontSize=16,
            leading=20,
            textColor=colors.HexColor("#111827"),
        ),
        "subtitle": ParagraphStyle(
            "DocSubtitle",
            parent=base["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#4B5563"),
        ),
        "banner": ParagraphStyle(
            "SimBanner",
            parent=base["Normal"],
            fontName="Helvetica-Bold",
            fontSize=8.5,
            leading=11,
            textColor=colors.HexColor("#92400E"),
            alignment=1,  # Center
        ),
        "heading": ParagraphStyle(
            "SectionHeading",
            parent=base["Normal"],
            fontName="Helvetica-Bold",
            fontSize=10.5,
            leading=14,
            textColor=colors.HexColor("#1F2937"),
            spaceBefore=6,
            spaceAfter=3,
        ),
        "body": ParagraphStyle(
            "BodySmall",
            parent=base["Normal"],
            fontName="Helvetica",
            fontSize=8,
            leading=10.5,
            textColor=colors.HexColor("#374151"),
        ),
        "body_bold": ParagraphStyle(
            "BodySmallBold",
            parent=base["Normal"],
            fontName="Helvetica-Bold",
            fontSize=8,
            leading=10.5,
            textColor=colors.HexColor("#111827"),
        ),
        "table_cell": ParagraphStyle(
            "TableCell",
            parent=base["Normal"],
            fontName="Helvetica",
            fontSize=7.5,
            leading=9.5,
            textColor=colors.HexColor("#1F2937"),
        ),
        "table_header": ParagraphStyle(
            "TableHeader",
            parent=base["Normal"],
            fontName="Helvetica-Bold",
            fontSize=7.5,
            leading=9.5,
            textColor=colors.HexColor("#FFFFFF"),
        ),
        "limitations": ParagraphStyle(
            "Limitations",
            parent=base["Normal"],
            fontName="Helvetica-Oblique",
            fontSize=7,
            leading=9,
            textColor=colors.HexColor("#6B7280"),
        ),
    }
    return styles


def generate_ward_brief_pdf(
    zone_dict: Dict[str, Any],
    sim_context: Dict[str, Any]
) -> bytes:
    """
    Generates an exact 1-page Ward Heat-Action Brief for municipal field teams.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=30,
        bottomMargin=30,
    )
    styles = _build_styles()
    story = []

    # 1. Header & Title
    zone_name = zone_dict.get("name", "Unknown Zone")
    zone_id = zone_dict.get("id", "Z00")
    t_peak = sim_context.get("ambient_temp_c", 45.0)
    outage_h = sim_context.get("outage_hours", 2.0)

    story.append(Paragraph(f"WARD HEAT-ACTION BRIEF: {zone_name.upper()} ({zone_id})", styles["title"]))
    story.append(Paragraph(
        f"Simulated Operational Briefing &middot; Raipur Municipal Corporation Planning Area &middot; Generated {datetime.now(timezone.utc).strftime('%d %b %Y, %H:%M UTC')}",
        styles["subtitle"]
    ))
    story.append(Spacer(1, 4))

    # 2. Mandatory Simulation Disclaimer Banner
    banner_data = [[
        Paragraph(
            "<b>SIMULATION ONLY – NOT AN OFFICIAL WARNING</b><br/>"
            "This document is a synthetic research simulation brief generated by AGNAYA for emergency planning exercises. "
            "It does not constitute an official warning or directive from IMD, NDMA, RMC, or CSPDCL.",
            styles["banner"]
        )
    ]]
    banner_table = Table(banner_data, colWidths=[540])
    banner_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#FEF3C7")),
        ("BORDER", (0, 0), (-1, -1), 1, colors.HexColor("#F59E0B")),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(banner_table)
    story.append(Spacer(1, 6))

    # 3. Demographic & Vulnerability Matrix
    story.append(Paragraph("1. Zone Demographic & Vulnerability Baseline", styles["heading"]))
    pop = zone_dict.get("population", 0)
    slum_pct = zone_dict.get("slum_pct", 0.0) * 100.0
    green_pct = zone_dict.get("green_cover_pct", 0.0) * 100.0
    ac_pct = zone_dict.get("ac_penetration_pct", 0.0) * 100.0
    elderly_pct = zone_dict.get("vulnerable_elderly_pct", 0.0) * 100.0

    demo_data = [
        [
            Paragraph("<b>Total Population</b>", styles["table_cell"]),
            Paragraph(f"{pop:,} persons", styles["table_cell"]),
            Paragraph("<b>Informal / Slum Share</b>", styles["table_cell"]),
            Paragraph(f"{slum_pct:.1f}% (CGI Tin Roofs)", styles["table_cell"]),
        ],
        [
            Paragraph("<b>Green Canopy Density</b>", styles["table_cell"]),
            Paragraph(f"{green_pct:.1f}%", styles["table_cell"]),
            Paragraph("<b>Household AC Access</b>", styles["table_cell"]),
            Paragraph(f"{ac_pct:.1f}%", styles["table_cell"]),
        ],
        [
            Paragraph("<b>Elderly Population (60+)</b>", styles["table_cell"]),
            Paragraph(f"{elderly_pct:.1f}%", styles["table_cell"]),
            Paragraph("<b>Data Confidence Status</b>", styles["table_cell"]),
            Paragraph(f"{zone_dict.get('confidence', 'MEDIUM')} (Census 2011/GIS)", styles["table_cell"]),
        ],
    ]
    t_demo = Table(demo_data, colWidths=[135, 135, 135, 135])
    t_demo.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F9FAFB")),
        ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#F9FAFB")),
        ("TOPPADDING", (0, 0), (-1, -1), 2.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
    ]))
    story.append(t_demo)
    story.append(Spacer(1, 6))

    # 4. Computed Microclimate & Thermal Trap
    story.append(Paragraph("2. Simulated Microclimate & Indoor Thermal Entrapment", styles["heading"]))
    indoor_temp = sim_context.get("indoor_temp_c", t_peak + 4.0 * zone_dict.get("slum_pct", 0.2) + 0.8 * outage_h)
    tin_trap = indoor_temp - t_peak
    hsri_score = sim_context.get("hsri_score", 62.5)
    risk_band = sim_context.get("risk_band", "HIGH")

    clim_data = [
        [
            Paragraph("<b>Ambient Temperature</b>", styles["table_cell"]),
            Paragraph(f"{t_peak:.1f}&deg;C", styles["table_cell"]),
            Paragraph("<b>Simulated Indoor Temp</b>", styles["table_cell"]),
            Paragraph(f"<b>{indoor_temp:.1f}&deg;C</b> (+{tin_trap:.1f}&deg;C trap)", styles["table_cell"]),
        ],
        [
            Paragraph("<b>Feeder Outage Duration</b>", styles["table_cell"]),
            Paragraph(f"{outage_h:.1f} hours", styles["table_cell"]),
            Paragraph("<b>Heuristic Risk Index</b>", styles["table_cell"]),
            Paragraph(f"<b>{hsri_score:.1f} / 100 ({risk_band})</b>", styles["table_cell"]),
        ],
    ]
    t_clim = Table(clim_data, colWidths=[135, 135, 135, 135])
    t_clim.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F9FAFB")),
        ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#F9FAFB")),
        ("TOPPADDING", (0, 0), (-1, -1), 2.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
    ]))
    story.append(t_clim)
    story.append(Spacer(1, 6))

    # 5. Infrastructure Linkages
    story.append(Paragraph("3. Lifeline Infrastructure Linkages", styles["heading"]))
    sub_id = zone_dict.get("substation", "S01")
    wp_id = zone_dict.get("water_pump", "WP01")
    infra_data = [
        [
            Paragraph("<b>Primary Substation</b>", styles["table_cell"]),
            Paragraph(f"{sub_id} (Grid dependent)", styles["table_cell"]),
            Paragraph("<b>Water Supply Node</b>", styles["table_cell"]),
            Paragraph(f"{wp_id} (Zonal booster/WTP)", styles["table_cell"]),
        ],
    ]
    t_infra = Table(infra_data, colWidths=[135, 135, 135, 135])
    t_infra.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F9FAFB")),
        ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#F9FAFB")),
        ("TOPPADDING", (0, 0), (-1, -1), 2.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
    ]))
    story.append(t_infra)
    story.append(Spacer(1, 6))

    # 6. Priority Municipal Intervention Checklist
    story.append(Paragraph("4. Recommended Municipal Intervention Checklist (Planning Only)", styles["heading"]))
    story.append(Paragraph(
        "&bull; <b>Potable Water Dispatch:</b> Deploy municipal tankers to high-density slum lanes lacking piped pressure.<br/>"
        "&bull; <b>Shaded Cooling Points:</b> Activate community cooling shelters with drinking water and misting fans.<br/>"
        "&bull; <b>Feeder Protection:</b> Prioritize local 33/11 kV feeder restoration to avoid compounding indoor tin-roof heat trapping.<br/>"
        "&bull; <b>Vulnerable Outreach:</b> ASHA / Anganwadi worker door-to-door welfare checks for elderly and bedridden residents.",
        styles["body"]
    ))
    story.append(Spacer(1, 6))

    # 7. Methodological Limitations & Disclaimer
    story.append(Paragraph("5. Scientific Limitations & What This Result Cannot Prove", styles["heading"]))
    story.append(Paragraph(
        "<b>Limitations:</b> This simulation employs an empirical indoor heat model pending in-situ data logger calibration "
        "(see docs/PILOT.md). It cannot prove individual clinical mortality, physiological heat stroke onset, or localized "
        "low-voltage phase outages. Population and slum shares are derived from Census 2011 and RMC master plan estimates. "
        "Official warnings and heat action plans are issued exclusively by the District Collector and IMD.",
        styles["limitations"]
    ))

    doc.build(story)
    return buffer.getvalue()


def generate_sitrep_pdf(
    sim_summary: Dict[str, Any],
    top_threats: List[Dict[str, Any]],
    allocated_fleet: Dict[str, int]
) -> bytes:
    """
    Generates a 2-page Municipal Situation Report (SITREP) for disaster managers.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=30,
        bottomMargin=30,
    )
    styles = _build_styles()
    story = []

    # 1. Header
    story.append(Paragraph("MUNICIPAL HEAT & GRID SITUATION REPORT (SITREP)", styles["title"]))
    story.append(Paragraph(
        f"Simulated Multi-Infrastructure Cascade Assessment &middot; Raipur, Chhattisgarh &middot; {datetime.now(timezone.utc).strftime('%d %b %Y, %H:%M UTC')}",
        styles["subtitle"]
    ))
    story.append(Spacer(1, 4))

    # 2. Disclaimer Banner
    banner_data = [[
        Paragraph(
            "<b>SIMULATION ONLY – NOT AN OFFICIAL WARNING</b><br/>"
            "This SITREP is generated by the AGNAYA research simulation engine for table-top disaster mitigation planning. "
            "It does not represent official statements of IMD, NDMA, CSPDCL, or Raipur Municipal Corporation.",
            styles["banner"]
        )
    ]]
    banner_table = Table(banner_data, colWidths=[540])
    banner_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#FEF3C7")),
        ("BORDER", (0, 0), (-1, -1), 1, colors.HexColor("#F59E0B")),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(banner_table)
    story.append(Spacer(1, 8))

    # 3. Macro Meteorological & Grid Status
    story.append(Paragraph("1. Meteorological Scenario & Transmission Demand Stress", styles["heading"]))
    t_peak = sim_summary.get("peak_temp_celsius", 45.0)
    d_peak = sim_summary.get("peak_demand_mw", 468.0)
    d_short = max(0.0, d_peak - 420.0)
    hours_saved = sim_summary.get("disruption_hours_saved", 14.62)
    resil_div = sim_summary.get("resilience_dividend_pct", 85.6)

    macro_data = [
        [
            Paragraph("<b>Scenario Peak Temperature</b>", styles["table_cell"]),
            Paragraph(f"{t_peak:.1f}&deg;C (IMD Mana Ref: 47.9&deg;C)", styles["table_cell"]),
            Paragraph("<b>Peak Electricity Demand</b>", styles["table_cell"]),
            Paragraph(f"<b>{d_peak:.1f} MW</b> (Baseline: 310 MW)", styles["table_cell"]),
        ],
        [
            Paragraph("<b>CSPDCL Contract Limit Shortfall</b>", styles["table_cell"]),
            Paragraph(f"<b>{d_short:.1f} MW</b> (Above 420 MW Limit)", styles["table_cell"]),
            Paragraph("<b>Resilience Dividend (MILP)</b>", styles["table_cell"]),
            Paragraph(f"<b>+{resil_div:.1f}%</b> ({hours_saved:.1f}h Deficit Saved)", styles["table_cell"]),
        ],
    ]
    t_macro = Table(macro_data, colWidths=[135, 135, 135, 135])
    t_macro.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F9FAFB")),
        ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#F9FAFB")),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]))
    story.append(t_macro)
    story.append(Spacer(1, 8))

    # 4. Critical Zone Ranking
    story.append(Paragraph("2. Priority Vulnerable Zones (HSRI Ranking)", styles["heading"]))
    zone_rows = [
        [
            Paragraph("<b>Rank</b>", styles["table_header"]),
            Paragraph("<b>Zone Name</b>", styles["table_header"]),
            Paragraph("<b>Population</b>", styles["table_header"]),
            Paragraph("<b>Slum Share</b>", styles["table_header"]),
            Paragraph("<b>HSRI Score</b>", styles["table_header"]),
            Paragraph("<b>Alert Tier</b>", styles["table_header"]),
            Paragraph("<b>Top Vulnerability Factor</b>", styles["table_header"]),
        ]
    ]
    for idx, z in enumerate(top_threats[:5], start=1):
        zone_rows.append([
            Paragraph(f"#{idx}", styles["table_cell"]),
            Paragraph(z.get("zone_name", z.get("zone_id", "Zone")), styles["table_cell"]),
            Paragraph(f"{z.get('population', 0):,}", styles["table_cell"]),
            Paragraph(f"{z.get('slum_pct', 0.0)*100:.0f}%", styles["table_cell"]),
            Paragraph(f"{z.get('threat_score', z.get('composite_risk_score', 0.0)):.1f}", styles["table_cell"]),
            Paragraph(z.get("alert_band", z.get("risk_tier", "HIGH")), styles["table_cell"]),
            Paragraph(z.get("top_driver", "Tin-roof heat trap"), styles["table_cell"]),
        ])
    t_zones = Table(zone_rows, colWidths=[30, 95, 65, 55, 55, 65, 175])
    t_zones.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1F2937")),
        ("TOPPADDING", (0, 0), (-1, -1), 2.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
    ]))
    story.append(t_zones)
    story.append(Spacer(1, 8))

    # 5. HiGHS MILP Resource Allocation
    story.append(Paragraph("3. HiGHS MILP Resource Allocation & Budget Execution", styles["heading"]))
    fleet_rows = [
        [
            Paragraph("<b>Intervention Measure</b>", styles["table_header"]),
            Paragraph("<b>Units Allocated</b>", styles["table_header"]),
            Paragraph("<b>Unit Sizing</b>", styles["table_header"]),
            Paragraph("<b>Unit Cost</b>", styles["table_header"]),
            Paragraph("<b>Total Expenditure</b>", styles["table_header"]),
        ]
    ]
    interv_meta = {
        "cooling_centre": ("Air-Conditioned Public Cooling Centre", "200 Persons", 2.5),
        "power_resilience": ("Mobile 2 MVA Standby DG Set", "2.0 MW", 8.0),
        "water_tankers": ("Municipal 10 kL Potable Water Tanker", "10 kL", 0.8),
        "hospital_surge": ("50-Bed Climate Controlled Triage Tent", "50 Beds", 15.0),
        "jal_jeevan": ("Community Shaded Drinking Water Kiosk", "500 Persons", 0.3),
    }
    total_spend = 0.0
    for k, v in allocated_fleet.items():
        if k in interv_meta:
            name, sizing, cost_unit = interv_meta[k]
            tot = v * cost_unit
            total_spend += tot
            fleet_rows.append([
                Paragraph(name, styles["table_cell"]),
                Paragraph(str(v), styles["table_cell"]),
                Paragraph(sizing, styles["table_cell"]),
                Paragraph(f"&inr; {cost_unit:.1f} Lakh", styles["table_cell"]),
                Paragraph(f"&inr; {tot:.1f} Lakh", styles["table_cell"]),
            ])
    fleet_rows.append([
        Paragraph("<b>Total Program Expenditure</b>", styles["table_cell"]),
        Paragraph("-", styles["table_cell"]),
        Paragraph("-", styles["table_cell"]),
        Paragraph("-", styles["table_cell"]),
        Paragraph(f"<b>&inr; {total_spend:.1f} Lakhs</b>", styles["table_cell"]),
    ])
    t_fleet = Table(fleet_rows, colWidths=[180, 75, 105, 80, 100])
    t_fleet.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1F2937")),
        ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#F3F4F6")),
        ("TOPPADDING", (0, 0), (-1, -1), 2.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
    ]))
    story.append(t_fleet)
    story.append(Spacer(1, 8))

    # 6. Planning Questions & Data Gaps
    story.append(Paragraph("4. Key Planning Inquiries & Municipal Data Gaps", styles["heading"]))
    story.append(Paragraph(
        "&bull; <b>Feeder Telemetry:</b> Need real-time SCADA feed from CSPTCL SLDC for S04, S05, S06 33kV distribution circuits.<br/>"
        "&bull; <b>Ward Boundaries:</b> Official RMC 70-ward shapefiles needed to migrate from 12 illustrative zones to ward-level planning.<br/>"
        "&bull; <b>In-Situ Indoor Calibration:</b> Datalogger deployment required in tin-roof dwellings (Birgaon/Gudhiyari) to validate thermal lag.<br/>"
        "&bull; <b>Hospital Surge Records:</b> Clinical heatstroke admission logs required from Pt. JNM Medical College to calibrate morbidity.",
        styles["body"]
    ))
    story.append(Spacer(1, 6))

    # 7. Scientific Limitations
    story.append(Paragraph("5. Scientific Limitations (What This Simulation Cannot Prove)", styles["heading"]))
    story.append(Paragraph(
        "This report is produced by a research simulation prototype. It does not prove clinical mortality, physiological heat stroke "
        "rates, or individual household thermal tolerance. All figures are based on deterministic coupled engineering equations (IEEE C57.91, "
        "IEEE 738, HSRI). Never use for statutory alerts or executive directives.",
        styles["limitations"]
    ))

    doc.build(story)
    return buffer.getvalue()
